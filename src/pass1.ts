/**
 * ONE PASS-1 CONFIGURATION, PLAYED — shared by the generator (src/simulate.ts) and the replay in
 * Step 19 (tests/steps/simulation.ts, through src/parallel.ts).
 *
 * Until 2026-09-24 the per-configuration loop lived inline in src/simulate.ts and Step 19 replayed
 * only the first REPLAY_ROUNDS = 10,000 rounds of each configuration with a second copy of the
 * running-total arithmetic. It is moved here unchanged — the same calls in the same order: the slot
 * from computeSlotFromBuffer (computeSlot with the key decoded once), the payout added as the
 * parseFloat of the bracket-0 multiplier string, a running-RTP snapshot at each
 * CONVERGENCE_SAMPLES point, lag-1 autocorrelation over the slot sequence and the runs test over
 * `slot > rows/2` — so that the committed outputs/simulation-results.json, generated by the inline
 * loop, is what this function must reproduce, and Step 19 proves it does on every run.
 */

import { computeSlotFromBuffer } from './rng';
import { lag1Autocorrelation, runsTest } from './stats';

export interface Pass1Played {
  slotCounts: number[];
  totalPayout: number;
  rtpSnapshots: Array<{ roundCount: number; rtp: number }>;
  lag1R: number;
  runsP: number;
}

/** Play `rounds` rounds of one configuration from its pinned seed pair. */
export function playPass1Config(
  rows: number,
  multipliers: number[],
  server: string,
  client: string,
  rounds: number,
  samples: readonly number[],
): Pass1Played {
  const key = Buffer.from(server, 'hex');
  const slotCounts = new Array(rows + 1).fill(0);
  const hitSequence = new Array(rounds);
  let totalPayout = 0;
  const rtpSnapshots: Array<{ roundCount: number; rtp: number }> = [];
  let nextSampleIdx = 0;
  for (let nonce = 0; nonce < rounds; nonce++) {
    const slot = computeSlotFromBuffer(key, client, nonce, rows);
    slotCounts[slot]++;
    hitSequence[nonce] = slot;
    totalPayout += multipliers[slot];
    if (nextSampleIdx < samples.length && (nonce + 1) === samples[nextSampleIdx]) {
      rtpSnapshots.push({ roundCount: nonce + 1, rtp: (totalPayout / (nonce + 1)) * 100 });
      nextSampleIdx++;
    }
  }
  const lag1R = lag1Autocorrelation(hitSequence);
  const median = rows / 2;
  const runs = runsTest(hitSequence.map((s: number) => s > median));
  return { slotCounts, totalPayout, rtpSnapshots, lag1R, runsP: runs.pValue };
}

/** A replay job as it crosses the worker boundary (structured-cloneable). */
export interface Pass1Job {
  rows: number;
  multipliers: number[];
  server: string;
  client: string;
  rounds: number;
  samples: number[];
}

/** Float64 slots one job fills: 17 slot counts, the sample points, totalPayout, lag1R, runsP. */
export const PASS1_MAX_SLOTS = 17;
export function pass1Slots(job: Pass1Job): number {
  return PASS1_MAX_SLOTS + job.samples.length + 3;
}

/** Worker kernel: play one configuration and pack the result. */
export function pass1ConfigKernel(job: unknown, out: Float64Array): void {
  const j = job as Pass1Job;
  const r = playPass1Config(j.rows, j.multipliers, j.server, j.client, j.rounds, j.samples);
  out.fill(NaN);
  for (let k = 0; k < r.slotCounts.length; k++) out[k] = r.slotCounts[k];
  for (let i = 0; i < r.rtpSnapshots.length; i++) out[PASS1_MAX_SLOTS + i] = r.rtpSnapshots[i].rtp;
  const t = PASS1_MAX_SLOTS + j.samples.length;
  out[t] = r.totalPayout;
  out[t + 1] = r.lag1R;
  out[t + 2] = r.runsP;
}

/** Unpack a kernel result. */
export function unpackPass1(job: Pass1Job, out: Float64Array): Pass1Played {
  const t = PASS1_MAX_SLOTS + job.samples.length;
  return {
    slotCounts: Array.from(out.subarray(0, job.rows + 1)),
    rtpSnapshots: job.samples.map((s, i) => ({ roundCount: s, rtp: out[PASS1_MAX_SLOTS + i] })),
    totalPayout: out[t],
    lag1R: out[t + 1],
    runsP: out[t + 2],
  };
}
